// Phase 2.3: compare each converted post with the same post in the scraped content file.
// Writes the report section of COPY_CHANGES.md (project root) and prints a summary.
// Usage: node scripts/blog-crosscheck.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/assets.mjs';
import { similarity, normWords, mdText } from './import-blog.mjs';

const CONTENT = path.join(ROOT, '..', 'drrozcohen_full_site_content.txt');
const BLOG = path.join(ROOT, 'src', 'content', 'blog');
const REPORT = path.join(ROOT, '..', 'COPY_CHANGES.md');

const text = fs.readFileSync(CONTENT, 'utf8');
const blocks = text.split(/^-{20,}\s*$/m);
const posts = new Map();
for (let i = 0; i < blocks.length; i++) {
  const head = blocks[i];
  const url = head.match(/^URL: https:\/\/drrozcohen\.com\/(\d{4}\/\d{2}\/\d{2}\/[^\s/]+)/m);
  if (!/^BLOG: /m.test(head) || !url) continue;
  const body = (blocks[i + 1] || '')
    .split(/^OUTBOUND LINKS:/m)[0]
    .replace(/^NOTE: .*$/gm, '')
    .replace(/^\[Note: .*\]$/gm, '');
  posts.set(url[1].split('/').pop(), body.trim());
}

const strip = (s) => s.replace(/^\s*[-*]\s+/gm, '').replace(/^\s*\d+[.)]\s+/gm, '');
const rows = [];
const details = [];
for (const file of fs.readdirSync(BLOG).filter((f) => f.endsWith('.md'))) {
  const slug = file.replace(/\.md$/, '');
  const md = fs.readFileSync(path.join(BLOG, file), 'utf8').split(/^---$/m).slice(2).join('---');
  const mdWords = normWords(mdText(md));
  const src = posts.get(slug);
  if (src === undefined) { rows.push({ slug, sim: null }); continue; }
  const srcWords = normWords(strip(src));
  const sim = similarity(mdWords, srcWords);
  rows.push({ slug, sim });
  if (sim < 0.98) {
    const mdJoined = ' ' + mdWords.join(' ') + ' ';
    const missing = src.split('\n').map((l) => l.trim()).filter(Boolean)
      .filter((l) => { const w = normWords(strip(l)); return w.length >= 3 && !mdJoined.includes(' ' + w.join(' ') + ' '); });
    details.push({ slug, sim, missing });
  }
}
rows.sort((a, b) => (a.sim ?? -1) - (b.sim ?? -1));
const under = rows.filter((r) => r.sim !== null && r.sim < 0.98);
const missingSrc = rows.filter((r) => r.sim === null);
console.log(`Posts compared: ${rows.length - missingSrc.length}. Under 98%: ${under.length}. Not in content file: ${missingSrc.length}`);

let out = fs.readFileSync(REPORT, 'utf8').split('\n## Blog verbatim cross-check')[0].trimEnd();
out += `

## Blog verbatim cross-check

Generated by \`build/scripts/blog-crosscheck.mjs\`. Word-level similarity (2 x LCS / total words) between each converted post and the same post in \`drrozcohen_full_site_content.txt\`.

**Finding:** the content file is not a verbatim copy of the blog. For many posts the scraper summarised, shortened or restructured the text (dropped paragraphs, merged sentences, rewrote lists, "fixed" Roz's typos such as "one small step at time"). The live site is the source of truth, so every post body was imported from the live page:

- 25 posts (2021 to Jan 29 2025) from the WordPress post HTML (\`.et_pb_post_content\`).
- 28 posts (Jan 31 2025 onward) are LinkedIn embeds on the live site (the WordPress body is only an \`<iframe>\`). Their text was imported from the public LinkedIn embed (\`linkedinEmbed\` in frontmatter), which is exactly what visitors see on drrozcohen.com today.

Each Markdown file matches its live source at 99.1% to 100% (\`scripts/blog-import-report.json\`; the sub-100% cases are list numerals that now render as \`<ol>\` numbers). So no post was "fixed" to match the content file. Posts below 98% against the content file are listed with the content-file lines that do not appear word for word in the live text, for the record.

| Post | Similarity to content file |
|---|---|
${rows.map((r) => `| ${r.slug} | ${r.sim === null ? 'not in content file' : (r.sim * 100).toFixed(1) + '%'} |`).join('\n')}

### Posts under 98%: content-file lines not found verbatim in the live text

${details.map((d) => `#### ${d.slug} (${(d.sim * 100).toFixed(1)}%)\n\n${d.missing.slice(0, 12).map((l) => `- ${l.length > 160 ? l.slice(0, 157) + '...' : l}`).join('\n')}${d.missing.length > 12 ? `\n- (+${d.missing.length - 12} more lines)` : ''}`).join('\n\n')}
`;
fs.writeFileSync(REPORT, out);
console.log('Wrote report to COPY_CHANGES.md');
