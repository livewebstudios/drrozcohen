// Phase 7 URL audit: every URL in the live WordPress sitemaps (plus common WP extras) must
// either build in dist/ or match a rule in public/_redirects. Writes ../URL_AUDIT.md.
// Usage: node scripts/url-audit.mjs   (run after `npm run build`)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, UA, sleep } from './lib/assets.mjs';

const DIST = path.join(ROOT, 'dist');
const SITEMAPS = [
  'wp-sitemap-posts-post-1.xml',
  'wp-sitemap-posts-page-1.xml',
  'wp-sitemap-posts-project-1.xml',
  'wp-sitemap-taxonomies-category-1.xml',
  'wp-sitemap-taxonomies-project_category-1.xml',
];
const EXTRAS = ['/contact/', '/feed/', '/wp-admin/', '/wp-login.php', '/author/rozcohen/', '/category/uncategorized/', '/tag/inclusion/', '/blog/page/2/', '/home/', '/2022/01/12/how-can-you-create-a-sense-of-belonging-within-your-organization/feed/'];

async function liveUrls() {
  const urls = new Set();
  for (const sm of SITEMAPS) {
    const res = await fetch(`https://drrozcohen.com/${sm}`, { headers: { 'User-Agent': UA } });
    await sleep(250);
    const xml = await res.text();
    for (const m of xml.matchAll(/<loc>([^<]+)<\/loc>/g)) urls.add(new URL(m[1]).pathname);
  }
  EXTRAS.forEach((u) => urls.add(u));
  return [...urls];
}

function parseRedirects() {
  return fs
    .readFileSync(path.join(ROOT, 'public', '_redirects'), 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'))
    .map((l) => {
      const [from, to, status] = l.split(/\s+/);
      const re = new RegExp(
        '^' + from.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/:(\w+)/g, '(?<$1>[^/]+)').replace(/\*$/, '(?<splat>.*)') + '$',
      );
      return { from, to, status, re };
    });
}

const built = (p) => {
  const clean = decodeURIComponent(p);
  const f = clean.endsWith('/') ? path.join(DIST, clean, 'index.html') : path.join(DIST, clean);
  return fs.existsSync(f);
};

const urls = (await liveUrls()).sort();
const rules = parseRedirects();
const rows = [];
let missing = 0;
for (const u of urls) {
  if (built(u)) { rows.push([u, 'built', '']); continue; }
  const rule = rules.find((r) => r.re.test(u));
  if (rule) {
    const m = u.match(rule.re);
    let target = rule.to;
    for (const [k, v] of Object.entries(m.groups || {})) target = target.replace(`:${k}`, v);
    const ok = built(target) || target === '/rss.xml' ? 'ok' : 'TARGET MISSING';
    if (ok !== 'ok') missing++;
    rows.push([u, `${rule.status} redirect`, `${target} (${ok})`]);
  } else {
    missing++;
    rows.push([u, 'MISSING', '']);
  }
}
const counts = rows.reduce((a, r) => ((a[r[1]] = (a[r[1]] || 0) + 1), a), {});
const md = `# URL Audit

Generated by \`build/scripts/url-audit.mjs\` on ${new Date().toISOString().slice(0, 10)} against the live WordPress sitemaps (${SITEMAPS.join(', ')}) plus common WordPress extras.

**Result:** ${urls.length} URLs checked. ${Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join(', ')}. Unresolved: **${missing}**.

| Live URL | Status | Target |
|---|---|---|
${rows.map((r) => `| \`${r[0]}\` | ${r[1]} | ${r[2] ? '`' + r[2] + '`' : ''} |`).join('\n')}
`;
fs.writeFileSync(path.join(ROOT, '..', 'URL_AUDIT.md'), md);
console.log(`URLs: ${urls.length}`, counts, `unresolved: ${missing}`);
if (missing) process.exitCode = 1;
